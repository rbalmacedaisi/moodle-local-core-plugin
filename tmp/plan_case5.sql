SELECT '==REOPENING / STATUS CHANGE EVENTS FOR CM 9554==' as '';
SELECT id, eventname, action, userid, relateduserid, from_unixtime(timecreated) dt, other FROM isi_logstore_standard_log WHERE contextinstanceid = 9554 AND eventname LIKE '%status%' ORDER BY timecreated;
SELECT '==CONFIGURACI?N ASSIGN 519 (attemptreopenmethod, etc.) ==';
SELECT id, course, name, attemptreopenmethod, maxattempts, timemodified FROM isi_assign WHERE id = 519;
SELECT '==USER OVERRIDE FOR USER 2735==' as '';
SHOW TABLES LIKE 'isi_assign_over%';
SELECT * FROM isi_assign_overrides WHERE assignment = 519 AND userid = 2735;
SELECT '==TOTAL SUBMISSIONS BY STATUS FOR ASSIGN 519==' as '';
SELECT status, COUNT(*) FROM isi_assign_submission WHERE assignment = 519 GROUP BY status;
SELECT '==REOPENED SUBMISSIONS FOR ASSIGN 519==' as '';
SELECT s.id, s.userid, u.firstname, u.lastname, s.attemptnumber, from_unixtime(s.timecreated) tc, from_unixtime(s.timemodified) tm FROM isi_assign_submission s JOIN isi_user u ON u.id = s.userid WHERE s.assignment = 519 AND s.status = 'reopened';
SELECT '==REOPENED STUDENT 2735==';
SELECT s.id, s.assignment, s.userid, s.status, from_unixtime(s.timecreated) tc, from_unixtime(s.timemodified) tm, s.attemptnumber FROM isi_assign_submission s WHERE s.assignment = 519 AND s.userid = 2735;
