SELECT id, course, name, duedate, timemodified, attemptreopenmethod, maxattempts FROM isi_assign WHERE id = 519;
SELECT '==CHECK ASSIGN_OVERRIDES FOR 519==' as '';
SELECT id, assignid, groupid, userid, duedate, cutoffdate FROM isi_assign_overrides WHERE assignid = 519;
SELECT '==COURSE_MODULE 9554 FULL==' as '';
SELECT id, course, section, instance, module, added, deletioninprogress, visible, completion FROM isi_course_modules WHERE id = 9554;
SELECT '==ALL ASSIGNS IN COURSE 87 WITH CAPAS O PALABRA METEOROLOGIA==' as '';
SELECT id, course, name, duedate, timemodified FROM isi_assign WHERE course = 87 AND (name LIKE '%CAPAS%' OR name LIKE '%PALABRA%' OR name LIKE '%TAREA%2%' OR name LIKE '%DEFINICION%PALABRA%');
SELECT '==ALL GRADED SUBMISSIONS IN ASSIGN 519==' as '';
SELECT s.id, s.userid, u.firstname, u.lastname, s.status, s.attemptnumber, s.latest, ag.grade FROM isi_assign_submission s JOIN isi_user u ON u.id = s.userid LEFT JOIN isi_assign_grades ag ON ag.assignment = 519 AND ag.userid = s.userid WHERE s.assignment = 519 ORDER BY s.userid;
SELECT '==STATUS DISTRIBUTION==' as '';
SELECT status, COUNT(*) AS n FROM isi_assign_submission WHERE assignment = 519 GROUP BY status;
